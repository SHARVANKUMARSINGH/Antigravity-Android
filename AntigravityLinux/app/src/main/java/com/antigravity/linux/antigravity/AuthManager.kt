package com.antigravity.linux.antigravity

import android.content.Context
import android.content.Intent
import android.net.Uri
import com.antigravity.linux.runtime.CommandExecutor
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.withContext
import java.io.File

data class AuthStatus(
    val isAuthenticated: Boolean = false,
    val userEmail: String? = null,
    val loginUrl: String = AntigravityManager.AUTH_URL,
    val statusMessage: String = "Not logged in"
)

class AuthManager(
    private val context: Context,
    private val rootfsDir: File,
    private val commandExecutor: CommandExecutor
) {
    private val _authStatus = MutableStateFlow(AuthStatus())
    val authStatus: StateFlow<AuthStatus> = _authStatus.asStateFlow()

    suspend fun checkAuthStatus(): AuthStatus = withContext(Dispatchers.IO) {
        val configDir = File(rootfsDir, "home/antigravity/.config/antigravity")
        val sessionFile = File(configDir, "session.json")

        if (sessionFile.exists() && sessionFile.length() > 0) {
            // Read session state without logging sensitive tokens
            try {
                val content = sessionFile.readText()
                val isAuthed = content.contains("\"authenticated\": true", ignoreCase = true) ||
                        content.contains("\"user\"", ignoreCase = true)
                val status = if (isAuthed) {
                    AuthStatus(
                        isAuthenticated = true,
                        userEmail = extractUserEmail(content),
                        statusMessage = "Authenticated with Google Antigravity account"
                    )
                } else {
                    AuthStatus(
                        isAuthenticated = false,
                        statusMessage = "Session expired or unauthenticated"
                    )
                }
                _authStatus.value = status
                return@withContext status
            } catch (_: Exception) {}
        }

        val defaultStatus = AuthStatus(
            isAuthenticated = false,
            statusMessage = "No active session found. Tap 'Open Antigravity Login' to authenticate."
        )
        _authStatus.value = defaultStatus
        defaultStatus
    }

    /**
     * Launches the official web browser to complete authentication.
     */
    fun openLoginBrowser() {
        val intent = Intent(Intent.ACTION_VIEW, Uri.parse(AntigravityManager.AUTH_URL)).apply {
            flags = Intent.FLAG_ACTIVITY_NEW_TASK
        }
        context.startActivity(intent)
    }

    /**
     * Fetches the local login callback link generated by the Antigravity desktop client.
     */
    suspend fun fetchLoginLink(): String? = withContext(Dispatchers.IO) {
        val linkFile = File(rootfsDir, "home/antigravity/.antigravity_auth_link")
        if (linkFile.exists() && linkFile.canRead()) {
            val link = linkFile.readText().trim()
            if (link.startsWith("https://") || link.startsWith("antigravity://")) {
                return@withContext link
            }
        }

        // Check if antigravity process printed a login link in its log
        val logFile = File(rootfsDir, "home/antigravity/.antigravity.log")
        if (logFile.exists() && logFile.canRead()) {
            val lines = logFile.readLines().takeLast(50)
            for (line in lines) {
                if (line.contains("https://antigravity.google/auth?token=") ||
                    line.contains("https://accounts.google.com/o/oauth2")
                ) {
                    val url = line.substring(line.indexOf("https://")).split(" ")[0].trim()
                    return@withContext url
                }
            }
        }
        null
    }

    private fun extractUserEmail(json: String): String? {
        val regex = "\"email\":\\s*\"([^\"]+)\"".toRegex()
        return regex.find(json)?.groupValues?.getOrNull(1)
    }
}
